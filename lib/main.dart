final navigatorKey = GlobalKey<NavigatorState>();

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  // Something on screen at once: Android only removes its launch screen
  // (the icon) once Flutter draws a first frame. Waiting for Firebase first
  // would leave the icon forever if an initialisation step hangs.
  runApp(const _StartupScreen());
  try {
    await SystemChrome.setPreferredOrientations([DeviceOrientation.portraitUp]);
    await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform)
        .timeout(const Duration(seconds: 20));

    final family = FamilyService(FirebaseFirestore.instance, FirebaseAuth.instance);
    await family.init();
    final settings = DeviceSettings();
    await settings.load();

    runApp(PitchouneApp(family: family, settings: settings));
  } catch (e, stack) {
    debugPrint('Startup failed: $e\n$stack');
    runApp(_StartupScreen(error: e));
  }
}

/// Shown while the app starts, or with the reason it could not start.
class _StartupScreen extends StatelessWidget {
  const _StartupScreen({this.error});
  final Object? error;

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      debugShowCheckedModeBanner: false,
      home: Scaffold(
        backgroundColor: kBackgroundTop,
        body: Center(
          child: Padding(
            padding: const EdgeInsets.all(32),
            child: error == null
                ? const CircularProgressIndicator()
                : Column(
                    mainAxisSize: MainAxisSize.min,
                    children: [
                      const Icon(Icons.error_outline_rounded, size: 64, color: Colors.redAccent),
                      const SizedBox(height: 16),
                      const Text(
                        'Pitchoune Timer could not start',
                        style: TextStyle(fontSize: 22, fontWeight: FontWeight.w900, color: kInk),
                      ),
                      const SizedBox(height: 12),
                      SelectableText('$error', textAlign: TextAlign.center),
                    ],
                  ),
          ),
        ),
      ),
    );
  }
}

class PitchouneApp extends StatelessWidget {
  const PitchouneApp({super.key, required this.family, required this.settings});
  final FamilyService family;
  final DeviceSettings settings;

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Pitchoune Timer',
      navigatorKey: navigatorKey,
      debugShowCheckedModeBanner: false,
      theme: ThemeData(
        useMaterial3: true,
        colorSchemeSeed: kPurple,
        scaffoldBackgroundColor: kBackgroundTop,
        snackBarTheme: const SnackBarThemeData(behavior: SnackBarBehavior.floating),
      ),
      // No family yet on this device: set one up. Otherwise, the family's home.
      home: ListenableBuilder(
        listenable: family,
        builder: (context, _) {
          final familyId = family.familyId;
          final deviceId = family.deviceId;
          if (familyId == null || deviceId == null) return FamilyScreen(family: family);
          return _FamilyHome(
            key: ValueKey(familyId),
            family: family,
            settings: settings,
            familyId: familyId,
            deviceId: deviceId,
          );
        },
      ),
    );
  }
}

/// Owns the [ChildrenStore] of one family for as long as this device belongs
/// to it, and shows the root screen of the tablet's mode.
class _FamilyHome extends StatefulWidget {
  const _FamilyHome({
    super.key,
    required this.family,
    required this.settings,
    required this.familyId,
    required this.deviceId,
  });

  final FamilyService family;
  final DeviceSettings settings;
  final String familyId;
  final String deviceId;

  @override
  State<_FamilyHome> createState() => _FamilyHomeState();
}

class _FamilyHomeState extends State<_FamilyHome> {
  late final ChildrenStore _store = ChildrenStore(
    FirestoreBackend(FirebaseFirestore.instance, widget.familyId),
    deviceId: widget.deviceId,
  );
  final _parent = ParentLock();
  bool _ready = false;

  /// Child the tablet is set to, if it still exists in the family.
  String? get _childModeId {
    final id = widget.settings.childId;
    return widget.settings.childMode && id != null && _store.byId(id) != null ? id : null;
  }

  @override
  void initState() {
    super.initState();
    widget.settings.addListener(_syncChildMode);
    _store.load().then((_) {
      if (!mounted) return;
      setState(() => _ready = true);
      _syncChildMode();
      // A countdown was running when Android killed the app (or the alarm has
      // just relaunched it): reopen its screen straight away. In child mode,
      // the root timer screen resumes it itself (see build).
      final session = _store.session;
      if (session != null && session.childId != _childModeId) {
        WidgetsBinding.instance.addPostFrameCallback((_) {
          navigatorKey.currentState?.push(
            timerRoute(_store, session.childId, parent: _parent, resume: session),
          );
        });
      }
    });
  }

  /// Starts or stops the native service that reopens the app at every unlock.
  void _syncChildMode() => Screen.setChildMode(_childModeId != null);

  @override
  void dispose() {
    widget.settings.removeListener(_syncChildMode);
    _store.dispose();
    _parent.dispose();
    super.dispose();
  }

  void _openSettings() {
    navigatorKey.currentState?.push(MaterialPageRoute<void>(
      builder: (_) => SettingsScreen(settings: widget.settings, store: _store),
    ));
  }

  @override
  Widget build(BuildContext context) {
    if (!_ready) {
      return const Scaffold(body: Center(child: CircularProgressIndicator()));
    }
    return ListenableBuilder(
      listenable: widget.settings,
      builder: (context, _) {
        final childId = _childModeId;
        // Child mode: straight to this child's countdown, no list of children.
        if (childId != null) {
          final session = _store.session;
          return TimerScreen(
            key: ValueKey(childId),
            store: _store,
            childId: childId,
            parent: _parent,
            resume: session?.childId == childId ? session : null,
            standalone: true,
            onOpenSettings: _openSettings,
          );
        }
        return HomeScreen(
          store: _store,
          parent: _parent,
          familyCode: FamilyService.format(widget.familyId),
          onLeaveFamily: widget.family.leave,
          onOpenSettings: _openSettings,
        );
      },
    );
  }
}
